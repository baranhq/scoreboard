import {mkdirSync,readFileSync,writeFileSync,copyFileSync} from 'node:fs';
mkdirSync('public/fonts',{recursive:true});
let css='/* Static WOFF2 subsets; generated by scripts/fonts.mjs from OFL-1.1 sources. */\n';
for(const [family,weights] of [['inter',[400,500,600]],['inter-tight',[500,600,700]]]) {
 for(const subset of ['latin','latin-ext','cyrillic']) for(const weight of weights) {
  const directory=`node_modules/@fontsource/${family}`;
  const source=readFileSync(`${directory}/${weight}.css`,'utf8');
  const block=source.split('@font-face').find(part=>part.includes(`/${family}-${subset}-${weight}-normal.woff2`));
  const range=block?.match(/unicode-range:\s*([^;]+);/)?.[1];
  const file=`${family}-${subset}-${weight}-normal.woff2`;
  if(!range)throw new Error(`Missing unicode range: ${file}`);
  copyFileSync(`${directory}/files/${file}`,`public/fonts/${file}`);
  css+=`@font-face { font-family: '${family==='inter'?'Inter':'Inter Tight'}'; font-style: normal; font-display: swap; font-weight: ${weight}; src: url('/fonts/${file}') format('woff2'); unicode-range: ${range}; }\n`;
 }
}
writeFileSync('app/font-faces.css',css);
