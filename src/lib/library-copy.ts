export type LibraryCopy = { [Key in keyof (typeof copy)["en"]]: string };
export const libraryCopy: Record<Lang, LibraryCopy> = copy;

export function projectCount(count: number, lang: Lang): string {
  const formatted = new Intl.NumberFormat(locale[lang]).format(count);
  const plural = new Intl.PluralRules(locale[lang]).select(count);
  if (count === 1) return libraryCopy[lang].oneProject;
  if (lang === "bg") return `${formatted} таблици`;
  if (lang === "tr") return `${formatted} tablo`;
  return plural === "one" ? `${formatted} project` : `${formatted} projects`;
}

export const locale: Record<Lang, string> = { en: "en-GB", bg: "bg-BG", tr: "tr-TR" };

export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}
